(function(){
  /* CTP Phase II panel — reads article data from the #p2-data JSON block
     generated by Hugo from content/phase-ii/*.md. The body is the article's
     rendered HTML (from markdown), inserted as-is, as before.
     The sidebar menu is server-rendered as links, so it exists on every page;
     the accordions are wired here on every page. The panel only exists on the
     homepage, where the menu is rebuilt as buttons that render into it. */
  function wireP2Toggles(){
    [].slice.call(document.querySelectorAll('.p2-acc-head')).forEach(function(hd){
      hd.addEventListener('click',function(){
        var list=hd.parentNode.querySelector('.p2-acc-list');
        if(!list) return;
        var open=list.classList.toggle('hidden')===false; if(open) list.removeAttribute('hidden');
        hd.setAttribute('aria-expanded', open?'true':'false');
        var c=hd.querySelector('.p2-caret'); if(c) c.textContent=open?'▾':'▸';
      });
    });
  }
  var panel=document.getElementById('p2Panel');
  var dataEl=document.getElementById('p2-data');
  if(!panel || !dataEl){
    wireP2Toggles();
    var m2=window.location.pathname.match(/\/phase-ii\/(ctp-p2-[a-z0-9-]+)\//i);
    if(m2){
      var cur2=document.querySelector('.p2-item[data-p2="'+m2[1].toUpperCase()+'"]');
      if(cur2){
        cur2.classList.add('is-active');
        var list2=cur2.closest('.p2-acc-list');
        if(list2 && list2.classList.contains('hidden')){
          list2.classList.remove('hidden'); list2.removeAttribute('hidden');
          var head2=list2.parentNode.querySelector('.p2-acc-head');
          if(head2){ head2.setAttribute('aria-expanded','true'); var c2=head2.querySelector('.p2-caret'); if(c2) c2.textContent='▾'; }
        }
      }
    }
    return;
  }
  var P2_ITEMS=JSON.parse(dataEl.textContent);
  var P2_GROUPS=["New Articles", "Overview", "Core Principles", "Deep Papers", "Cosmology & Funding", "Movement & Trends"];
  var byId={};
  P2_ITEMS.forEach(function(a){ byId[a.id]=a; });
  function esc(s){ return String(s).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;'); }
  function menuHTML(){
    var h='';
    P2_GROUPS.forEach(function(g){
      h+='<div class="p2-acc"><button type="button" class="p2-acc-head" aria-expanded="false">'+esc(g)+'<span class="p2-caret" aria-hidden="true">▸</span></button><ul class="p2-acc-list hidden">';
      P2_ITEMS.forEach(function(a){
        if(a.group===g) h+='<li><button type="button" class="p2-item" data-p2="'+esc(a.id)+'"><span class="p2-item-id">'+esc(a.id)+'</span>'+esc(a.title)+'</button></li>';
      });
      h+='</ul></div>';
    });
    return h;
  }
  ['p2MenuDesktop','p2MenuMobile'].forEach(function(mid){
    var m=document.getElementById(mid);
    if(m) m.innerHTML=menuHTML();
  });
  var current=null;
  function typesetP2(){ if(window.MathJax && MathJax.typesetPromise){ MathJax.typesetPromise([panel]).catch(function(){}); } }
  function showP2(id,scroll){
    var a=byId[id]; if(!a) return;
    current=id;
    var h='';
    h+='<div class="p2-panel-top"><span class="p2-id">'+esc(a.id)+'</span><span class="p2-date">'+esc(a.date||'')+'</span></div>';
    h+='<div class="p2-panel-body" id="'+esc(a.id)+'">';
    h+='<h3 class="p2-title">'+esc(a.title)+'</h3>';
    if(a.draft) h+='<p class="p2-draft-note">Draft &mdash; expanded-form draft, as marked in the source file</p>';
    h+='<div class="p2-text">'+a.body+'</div>';
    if(a.note) h+='<p class="p2-note">'+esc(a.note)+'</p>';
    if(a.local){ h+='<p class="p2-source">Source: CTPVerse Dashboard &middot; CTP Phase II &middot; '+esc(a.source)+'</p>'; }
    else h+='<p class="p2-source">Source: CTP is Disclosure repository, <a href="https://github.com/CTPIDM/ctp-is-disclosure" target="_blank" rel="noopener">github.com/CTPIDM/ctp-is-disclosure</a> &middot; File: '+esc(a.source)+'</p>';
    if(a.url) h+='<p class="p2-more"><a href="'+esc(a.url)+'">Read this article on its own page &raquo;</a></p>';
    h+='</div>';
    panel.innerHTML=h;
    typesetP2();
    [].slice.call(document.querySelectorAll('.p2-item')).forEach(function(b){
      var on=b.getAttribute('data-p2')===id;
      b.classList.toggle('is-active',on);
      if(on && scroll){
        var list=b.closest('.p2-acc-list');
        if(list && list.classList.contains('hidden')){
          list.classList.remove('hidden'); list.removeAttribute('hidden');
          var head=list.parentNode.querySelector('.p2-acc-head');
          if(head){ head.setAttribute('aria-expanded','true'); var c=head.querySelector('.p2-caret'); if(c) c.textContent='▾'; }
        }
      }
    });
    if(scroll){
      try{ history.replaceState(null,'','#'+id); }catch(e){}
      var sec=document.getElementById('phase2');
      var tgt=(window.innerWidth<=680)?panel:sec;
      if(tgt) tgt.scrollIntoView({block:'start'});
    }
  }
  [].slice.call(document.querySelectorAll('.p2-item')).forEach(function(b){
    b.addEventListener('click',function(){ showP2(b.getAttribute('data-p2'),true); });
  });
  wireP2Toggles();
  panel.addEventListener('click',function(e){
    var t=(e.target && e.target.closest)?e.target.closest('[data-p2-jump]'):null;
    if(t) showP2(t.getAttribute('data-p2-jump'),true);
  });
  var start='CTP-P2-001';
  if(location.hash && byId[location.hash.slice(1)]) start=location.hash.slice(1);
  showP2(start,false);
  window.addEventListener('load',typesetP2);
})();
