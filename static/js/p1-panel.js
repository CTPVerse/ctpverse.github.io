(function(){
  /* CTP Phase I Archive panel — reads article data from the #p1-data JSON block
     generated by Hugo from content/phase-i/*.md. Renders the article's HTML
     content (already rendered from markdown) instead of a paras array.
     The sidebar accordions work on every page; the panel only exists on the
     homepage, so on article/list pages the items navigate to their own pages. */
  function wireP1Toggles(){
    [].slice.call(document.querySelectorAll('.p1-acc-head')).forEach(function(h){
      h.addEventListener('click',function(){
        var list=h.parentNode.querySelector('.p1-acc-list');
        if(!list) return;
        var open=list.classList.toggle('hidden')===false; if(open) list.removeAttribute('hidden');
        h.setAttribute('aria-expanded', open?'true':'false');
        var c=h.querySelector('.p1-caret'); if(c) c.textContent=open?'\u25BE':'\u25B8';
      });
    });
  }
  wireP1Toggles();
  var panel=document.getElementById('p1Panel');
  var dataEl=document.getElementById('p1-data');
  if(!panel || !dataEl){
    [].slice.call(document.querySelectorAll('.p1-item')).forEach(function(b){
      b.addEventListener('click',function(){
        window.location.href='/phase-i/'+b.getAttribute('data-p1').toLowerCase()+'/';
      });
    });
    var m=window.location.pathname.match(/\/phase-i\/(ctp-p1-[a-z0-9-]+)\//i);
    if(m){
      var cur=document.querySelector('.p1-item[data-p1="'+m[1].toUpperCase()+'"]');
      if(cur){
        cur.classList.add('is-active');
        var list=cur.closest('.p1-acc-list');
        if(list && list.classList.contains('hidden')){
          list.classList.remove('hidden'); list.removeAttribute('hidden');
          var head=list.parentNode.querySelector('.p1-acc-head');
          if(head){ head.setAttribute('aria-expanded','true'); var c=head.querySelector('.p1-caret'); if(c) c.textContent='\u25BE'; }
        }
      }
    }
    return;
  }
  var P1_ARTICLES=JSON.parse(dataEl.textContent);
  var byId={};
  P1_ARTICLES.forEach(function(a){ byId[a.id]=a; });
  function esc(s){ return String(s).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;'); }
  var current=null;
  function showP1(id,scroll,keepClosed){
    var a=byId[id]; if(!a) return;
    current=id;
    var h='';
    h+='<div class="p1-panel-top"><span class="p1-id">'+esc(a.id)+(a.cf?' &middot; Original site viewpage ID: '+a.cf:'')+'</span><span class="p1-date">'+esc(a.date)+'</span></div>';
    h+='<div class="p1-panel-body" id="'+esc(a.id)+'">';
    h+='<h3 class="p1-title">'+esc(a.title)+'</h3>';
    h+='<div class="p1-img" role="img" aria-label="Image slot for article '+esc(a.id)+' — no image assigned yet"><span class="p1-img-label">Image slot</span><span class="p1-img-id">'+esc(a.id)+'</span><span class="p1-img-note">Image to be added for this article</span></div>';
    if(a.note==='removed2005'){
      h+='<div class="p1-soon"><b>2005 only — later removed from the site.</b><br>This title appears in the C-Domain Topics list on the original static site in February–March 2005. It does not appear in the later site maps or the ColdFusion portal navigation, and no article text for it was preserved in the archive, so none is shown here.</div>';
    }else if(a.note==='cfreq2005'){
      h+='<div class="p1-soon"><b>2005 only — later removed from the site.</b><br>C-frequency Existences has its own page in the early site (c_frequency_existences.htm, captured February 28, 2005), but that capture preserved only the navigation and the words Coming Soon — no article text. The topic was later folded into C-energy Frequencies / Group C-energy Frequency (GCF); see CTP-P1-012 and CTP-P1-013.</div>';
    }else if(!a.content || !a.content.trim()){
      h+='<div class="p1-soon"><b>Coming Soon — no article text in the archive.</b><br>This title appears in the original site\'s navigation, but the Wayback captures preserved it only as a navigation shell — no article text was archived for it, so none is shown here.</div>';
    }else{
      h+='<div class="p1-text">'+a.content+'</div>';
      if(a.note) h+='<p class="p1-note">'+esc(a.note)+'</p>';
    }
    if(a.url) h+='<p class="p1-more"><a href="'+esc(a.url)+'">Read this article on its own page &raquo;</a></p>';
    h+='</div>';
    panel.innerHTML=h;
    [].slice.call(document.querySelectorAll('.p1-item')).forEach(function(b){
      var on=b.getAttribute('data-p1')===id;
      b.classList.toggle('is-active',on);
      if(on && !keepClosed){
        var list=b.closest('.p1-acc-list');
        if(list && list.classList.contains('hidden')){
          list.classList.remove('hidden'); list.removeAttribute('hidden');
          var head=list.parentNode.querySelector('.p1-acc-head');
          if(head){ head.setAttribute('aria-expanded','true'); var c=head.querySelector('.p1-caret'); if(c) c.textContent='\u25BE'; }
        }
      }
    });
    if(scroll){
      try{ history.replaceState(null,'','#'+id); }catch(e){}
      var sec=document.getElementById('phase1-archive');
      var tgt=(window.innerWidth<=680)?panel:sec;
      if(tgt) tgt.scrollIntoView({block:'start'});
    }
  }
  [].slice.call(document.querySelectorAll('.p1-item')).forEach(function(b){
    b.addEventListener('click',function(){ showP1(b.getAttribute('data-p1'),true); });
  });
  var start='CTP-P1-001';
  if(location.hash && byId[location.hash.slice(1)]) start=location.hash.slice(1);
  showP1(start,false,true);
})();
